CREATE TABLE IF NOT EXISTS `MEMBERS` (
	`member_id` INTEGER UNSIGNED NOT NULL AUTO_INCREMENT,
	`member_name` VARCHAR(255) NOT NULL,
	`member_type` VARCHAR(255) NOT NULL,
	`joined_date` DATE NOT NULL,
	PRIMARY KEY(`member_id`)
);


CREATE TABLE IF NOT EXISTS `BOOKS` (
	`book_id` INTEGER UNSIGNED NOT NULL AUTO_INCREMENT,
	`title` VARCHAR(255) NOT NULL,
	`author` VARCHAR(255) NOT NULL,
	`category` VARCHAR(255) NOT NULL,
	`price` INTEGER NOT NULL,
	`copies_available` INTEGER NOT NULL,
	PRIMARY KEY(`book_id`)
);


CREATE TABLE IF NOT EXISTS `ISSUES` (
	`issues_id` INTEGER UNSIGNED NOT NULL AUTO_INCREMENT,
	`member_id` INTEGER NOT NULL DEFAULT foregin key,
	`book_id` INTEGER NOT NULL,
	`issue_date` DATE NOT NULL,
	`due_date` DATE NOT NULL,
	`return_date` DATE NOT NULL,
	PRIMARY KEY(`issues_id`)
);


